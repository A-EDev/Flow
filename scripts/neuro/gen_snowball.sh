#!/bin/sh
# Writes the Snowball stemmers the engine uses to app/src/main/java/org/tartarus/snowball from one
# pinned Snowball release. The output is byte-identical to the official libstemmer_java tarball of
# that release; never edit it by hand. Needs curl, tar, make and a C compiler.
# Run from anywhere: sh scripts/neuro/gen_snowball.sh
set -eu

VERSION=3.1.1
COMMIT=cd195b51e948a902a4312f023f4a14392516a543
SHA256=05b41be0ab869d5d66a417e0fc4a9b2ae064d60e8f4ffad773f1288b5ea5d6c1
LANGUAGES="english spanish portuguese french german italian russian"
RUNTIME="Among CharArraySequence SnowballProgram SnowballStemmer"

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
OUT="$ROOT/app/src/main/java/org/tartarus/snowball"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

curl -sSL -o "$WORK/snowball.tar.gz" "https://github.com/snowballstem/snowball/archive/$COMMIT.tar.gz"
if command -v sha256sum >/dev/null 2>&1; then
    echo "$SHA256  $WORK/snowball.tar.gz" | sha256sum -c - >/dev/null
else
    echo "$SHA256  $WORK/snowball.tar.gz" | shasum -a 256 -c - >/dev/null
fi
mkdir "$WORK/src"
tar -xzf "$WORK/snowball.tar.gz" -C "$WORK/src" --strip-components=1
make -C "$WORK/src" snowball >/dev/null

rm -rf "$OUT"
mkdir -p "$OUT/ext"
for class in $RUNTIME; do
    cp "$WORK/src/java/org/tartarus/snowball/$class.java" "$OUT/"
done
for language in $LANGUAGES; do
    (cd "$WORK/src" && ./snowball "algorithms/$language.sbl" -java -o "$OUT/ext/${language}Stemmer" -p org.tartarus.snowball.SnowballStemmer)
done
{
    echo "/*"
    sed 's/^/ * /; s/ *$//' "$WORK/src/COPYING"
    echo " */"
    echo
    echo "/** Snowball $VERSION ($COMMIT), generated by scripts/neuro/gen_snowball.sh. Do not edit. */"
    echo "package org.tartarus.snowball;"
} > "$OUT/package-info.java"
